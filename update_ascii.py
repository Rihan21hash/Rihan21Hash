for filename in ['dark.svg', 'light.svg']:
    with open(f'd:/VSC files/Github Profile/{filename}', 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Replace the existing <g> containing ASCII and the blinking cursor below it
    pattern = re.compile(r'    <!-- ASCII art group with float animation -->\s*<g font-family=.*?</g>\s*<!-- Blinking cursor on ASCII .*?</g>', re.DOTALL)
    
    if pattern.search(content):
        new_content = pattern.sub(xml, content)
        with open(f'd:/VSC files/Github Profile/{filename}', 'w', encoding='utf-8') as f:
            f.write(new_content)
        print(f'Successfully updated {filename}')
    else:
        print(f'Pattern not found in {filename}')
